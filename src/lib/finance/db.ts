/** All transactions, newest first; optional "YYYY-MM" filter on the date. */
export async function fetchTransactions(month?: string): Promise<Transaction[]> {
  const userId = await uid();
  const sb = getSupabase();
  let q = sb
    .from("transactions")
    .select()
    .eq("user_id", userId)
    .order("date_iso", { ascending: false })
    .order("created_at", { ascending: false });
  if (month) {
    const { from, to } = monthRange(month);
    q = q.gte("date_iso", from).lt("date_iso", to);
  }
  const { data, error } = await q;
  if (error) throw error;
  return ((data ?? []) as unknown as TransactionRow[]).map(toTransaction);
}

export async function insertTransaction(input: NewTransaction): Promise<Transaction> {
  assertPaise(input.amountPaise);
  assertDateISO(input.dateISO, "dateISO");
  const userId = await uid();
  const sb = getSupabase();
  const { data, error } = await sb
    .from("transactions")
    .insert({
      user_id: userId,
      type: input.type,
      amount_paise: input.amountPaise,
      category: input.category,
      note: input.note,
      date_iso: input.dateISO,
      pay_mode: input.payMode,
      ...(input.goalId ? { goal_id: input.goalId } : {}),
      ...(input.billId ? { bill_id: input.billId } : {}),
      ...(input.accountId ? { account_id: input.accountId } : {}),
      ...(input.toAccountId ? { to_account_id: input.toAccountId } : {}),
      tags: normalizeTags(input.tags),
      ...(input.recurringRuleId ? { recurring_rule_id: input.recurringRuleId } : {}),
    })
    .select()
    .single();
  if (error) throw error;
  return toTransaction(data as unknown as TransactionRow);
}

export async function updateTransaction(
  id: string,
  patch: Partial<Omit<Transaction, "id" | "createdAt">>,
): Promise<Transaction | undefined> {
  if (patch.amountPaise !== undefined) assertPaise(patch.amountPaise);
  if (patch.dateISO !== undefined) assertDateISO(patch.dateISO, "dateISO");
  const userId = await uid();
  const sb = getSupabase();
  const row: Record<string, unknown> = { updated_at: new Date().toISOString() };
  if (patch.type !== undefined) row["type"] = patch.type;
  if (patch.amountPaise !== undefined) row["amount_paise"] = patch.amountPaise;
  if (patch.category !== undefined) row["category"] = patch.category;
  if (patch.note !== undefined) row["note"] = patch.note;
  if (patch.dateISO !== undefined) row["date_iso"] = patch.dateISO;
  if (patch.payMode !== undefined) row["pay_mode"] = patch.payMode;
  if (patch.goalId !== undefined) row["goal_id"] = patch.goalId;
  if (patch.billId !== undefined) row["bill_id"] = patch.billId;
  if (patch.accountId !== undefined) row["account_id"] = patch.accountId;
  if (patch.toAccountId !== undefined) row["to_account_id"] = patch.toAccountId;
  if (patch.tags !== undefined) row["tags"] = normalizeTags(patch.tags);
  if (patch.recurringRuleId !== undefined) row["recurring_rule_id"] = patch.recurringRuleId;
  const { data, error } = await sb
    .from("transactions")
    .update(row)
    .eq("id", id)
    .eq("user_id", userId)
    .select()
    .single();
  if (isNoRows(error)) return undefined;
  if (error) throw error;
  return toTransaction(data as unknown as TransactionRow);
}

