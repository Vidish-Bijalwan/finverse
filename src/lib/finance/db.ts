/**
 * Deletes an account and re-points its transactions (and recurring rules) at
 * the default account, so no history is lost. Throws when the account is the
 * default or the last one — pick/set another default first.
 */
export async function deleteAccount(id: string): Promise<void> {
  const userId = await uid();
  const sb = getSupabase();
  const accounts = await fetchAccounts();
  const account = accounts.find((a) => a.id === id);
  if (!account) throw new Error("Account not found.");
  if (accounts.length === 1) {
    throw new Error("You need at least one account — create another before deleting this one.");
  }
  if (account.isDefault) {
    throw new Error("This is your default account. Set another account as default first.");
  }
  const fallback = accounts.find((a) => a.isDefault) ?? accounts.find((a) => a.id !== id);
  if (!fallback) throw new Error("No fallback account found.");
  for (const table of ["transactions", "recurring_rules"] as const) {
    const { error: e1 } = await sb
      .from(table)
      .update({ account_id: fallback.id })
      .eq("user_id", userId)
      .eq("account_id", id);
    if (e1) throw e1;
    const { error: e2 } = await sb
      .from(table)
      .update({ to_account_id: fallback.id })
      .eq("user_id", userId)
      .eq("to_account_id", id);
    if (e2) throw e2;
  }
  const { error } = await sb.from("accounts").delete().eq("id", id).eq("user_id", userId);
  if (error) throw error;
}

