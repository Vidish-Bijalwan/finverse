function monthRange(month: string): { from: string; to: string } {
  const m = /^(\d{4})-(\d{2})$/.exec(month);
  const y = Number(m?.[1] ?? 0);
  const mo = Number(m?.[2] ?? 0);
  if (!m || y < 1000 || mo < 1 || mo > 12) {
    throw new Error(`month must be "YYYY-MM", got "${month}"`);
  }
  const toY = mo === 12 ? y + 1 : y;
  const toM = mo === 12 ? 1 : mo + 1;
  return { from: `${month}-01`, to: `${toY}-${String(toM).padStart(2, "0")}-01` };
}

