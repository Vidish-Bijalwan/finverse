/**
 * Live balance: opening balance plus replayed transaction effects.
 * Expense debits, income credits; transfers debit the source account and
 * credit the destination account. Always consistent — edits/deletes flow
 * through automatically because the balance is derived, not stored.
 */
export function balanceForAccount(account: Account, transactions: Transaction[]): number {
  let balance = account.openingBalancePaise;
  for (const t of transactions) {
    if (t.type === "transfer") {
      if (t.accountId === account.id) balance -= t.amountPaise;
      if (t.toAccountId === account.id) balance += t.amountPaise;
    } else if (t.accountId === account.id) {
      balance += t.type === "income" ? t.amountPaise : -t.amountPaise;
    }
  }
  return balance;
}

/** Accounts with live balances, computed client-side from all transactions. */
export async function fetchAccountSummaries(): Promise<AccountSummary[]> {
  const [accounts, transactions] = await Promise.all([fetchAccounts(), fetchTransactions()]);
  return accounts.map((account) => ({
    account,
    balancePaise: balanceForAccount(account, transactions),
  }));
}

