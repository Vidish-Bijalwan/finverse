/**
 * Marks a bill paid (sets last_paid_on) AND inserts the matching expense
 * transaction against the default account.
 */
export async function markBillPaid(id: string, dateISO: string): Promise<Bill | undefined> {
  assertDateISO(dateISO, "dateISO");
  const userId = await uid();
  const sb = getSupabase();
  const now = new Date().toISOString();
  const { data, error } = await sb
    .from("bills")
    .update({ last_paid_on: dateISO, updated_at: now })
    .eq("id", id)
    .eq("user_id", userId)
    .select()
    .single();
  if (isNoRows(error)) return undefined;
  if (error) throw error;
  const bill = toBill(data as unknown as BillRow);
  const fallbackAccountId = await defaultAccountId();
  await insertTransaction({
    type: "expense",
    amountPaise: bill.amountPaise,
    category: bill.category,
    note: `${bill.name} bill paid`,
    dateISO,
    payMode: "UPI",
    ...(fallbackAccountId ? { accountId: fallbackAccountId } : {}),
    billId: bill.id,
    tags: [],
  });
  return bill;
}

/** Insert a new bill (id generated by the database). */
export async function insertBill(input: Omit<Bill, "id">): Promise<Bill> {
  const name = input.name.trim();
  if (!name) throw new Error("Bill name is required.");
  assertPaise(input.amountPaise);
  if (!Number.isInteger(input.dueDay) || input.dueDay < 1 || input.dueDay > 31) {
    throw new Error("Bill due day must be an integer between 1 and 31.");
  }
  if (input.lastPaidOn !== undefined) assertDateISO(input.lastPaidOn, "lastPaidOn");
  const userId = await uid();
  const sb = getSupabase();
  const { data, error } = await sb
    .from("bills")
    .insert({
      user_id: userId,
      name: name.slice(0, 60),
      amount_paise: input.amountPaise,
      due_day: input.dueDay,
      category: input.category,
      last_paid_on: input.lastPaidOn ?? null,
    })
    .select()
    .single();
  if (error) throw error;
  return toBill(data as unknown as BillRow);
}

/** Update a bill's fields. Returns undefined when the bill does not exist. */
export async function updateBill(
  id: string,
  patch: Partial<Omit<Bill, "id">>,
): Promise<Bill | undefined> {
  if (patch.name !== undefined && !patch.name.trim()) throw new Error("Bill name is required.");
  if (patch.amountPaise !== undefined) assertPaise(patch.amountPaise);
  if (
    patch.dueDay !== undefined &&
    (!Number.isInteger(patch.dueDay) || patch.dueDay < 1 || patch.dueDay > 31)
  ) {
    throw new Error("Bill due day must be an integer between 1 and 31.");
  }
  if (patch.lastPaidOn !== undefined) assertDateISO(patch.lastPaidOn, "lastPaidOn");
  const userId = await uid();
  const sb = getSupabase();
  const row: Record<string, unknown> = { updated_at: new Date().toISOString() };
  if (patch.name !== undefined) row["name"] = patch.name.trim().slice(0, 60);
  if (patch.amountPaise !== undefined) row["amount_paise"] = patch.amountPaise;
  if (patch.dueDay !== undefined) row["due_day"] = patch.dueDay;
  if (patch.category !== undefined) row["category"] = patch.category;
  if (patch.lastPaidOn !== undefined) row["last_paid_on"] = patch.lastPaidOn;
  const { data, error } = await sb
    .from("bills")
    .update(row)
    .eq("id", id)
    .eq("user_id", userId)
    .select()
    .single();
  if (isNoRows(error)) return undefined;
  if (error) throw error;
  return toBill(data as unknown as BillRow);
}

