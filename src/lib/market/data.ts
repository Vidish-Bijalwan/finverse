const BY_SYMBOL = new Map(STOCKS.map((s) => [s.symbol, s]));

export function getStock(symbol: string): StockInfo | undefined {
  return BY_SYMBOL.get(symbol.toUpperCase());
}

export const SECTORS: string[] = Array.from(new Set(STOCKS.map((s) => s.sector))).sort();

/** Median P/E of a sector — used for valuation comparisons in AI analysis. */
export function sectorMedianPE(sector: string): number {
  const pes = STOCKS.filter((s) => s.sector === sector)
    .map((s) => s.pe)
    .sort((a, b) => a - b);
  if (pes.length === 0) return 0;
  const mid = Math.floor(pes.length / 2);
  return pes.length % 2 === 1 ? pes[mid] : (pes[mid - 1] + pes[mid]) / 2;
}

/** Median 1Y return of a sector — used for momentum comparison. */
export function sectorMedianReturn(sector: string): number {
  const rs = STOCKS.filter((s) => s.sector === sector)
    .map((s) => s.oneYReturnPct)
    .sort((a, b) => a - b);
  if (rs.length === 0) return 0;
  const mid = Math.floor(rs.length / 2);
  return rs.length % 2 === 1 ? rs[mid] : (rs[mid - 1] + rs[mid]) / 2;
}
