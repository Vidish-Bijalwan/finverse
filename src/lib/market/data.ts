/**
 * Demo dataset for academic project — not live prices.
 *
 * ~40 Indian equities/ETF with plausible illustrative fundamentals used by the
 * FinVerse Markets module (portfolio, screener, stock detail). All money is in
 * integer paise, consistent with the finance store's paise convention.
 * These figures are static teaching data — do not treat them as market advice.
 */

export interface StockInfo {
  symbol: string;
  name: string;
  sector: string;
  /** Integer paise per unit. */
  pricePaise: number;
  /** Trailing P/E. */
  pe: number;
  /** Market capitalisation in ₹ crore. */
  marketCapCr: number;
  /** Dividend yield, percent. */
  divYield: number;
  /** Return on equity, percent. Null where not meaningful (ETF, insurers). */
  roe: number | null;
  /** Debt-to-equity ratio. Null where not meaningful (banks, insurers, ETF). */
  debtEquity: number | null;
  /** Earnings per share, integer paise. */
  epsPaise: number;
  /** 52-week high, integer paise. */
  high52wPaise: number;
  /** 52-week low, integer paise. */
  low52wPaise: number;
  /** 1-year price return, percent. */
  oneYReturnPct: number;
}

/** Market-cap bands used by the screener (₹ crore). */
export const MCAP_BANDS = {
  large: { label: "Large cap", min: 20000, hint: "> ₹20,000 Cr" },
  mid: { label: "Mid cap", min: 5000, max: 20000, hint: "₹5,000–20,000 Cr" },
  small: { label: "Small cap", max: 5000, hint: "< ₹5,000 Cr" },
} as const;

export type McapBand = keyof typeof MCAP_BANDS;

export function mcapBandOf(marketCapCr: number): McapBand {
  if (marketCapCr > 20000) return "large";
  if (marketCapCr >= 5000) return "mid";
  return "small";
}

